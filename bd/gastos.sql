CREATE TYPE tipo_movimiento AS ENUM (
    'ingreso',
    'gasto',
    'transferencia',
    'reintegro',
    'devolucion',
    'ajuste'
	'cuotas'
);

CREATE TYPE estado_movimiento AS ENUM (
    'pendiente',
    'confirmado',
    'cancelado'
);

CREATE TYPE tipo_cuenta AS ENUM (
    'efectivo',
    'cuenta_bancaria',
    'billetera_virtual',
    'tarjeta_credito',
    'ahorro',
    'inversion'
);

CREATE TYPE tipo_flujo AS ENUM (
    'ingreso',
    'gasto'
);

CREATE TABLE IF NOT EXISTS "usuario" (
	"id_usuario" uuid NOT NULL DEFAULT gen_random_uuid(),
	"nombre" TEXT NOT NULL,
	"correo" TEXT NOT NULL UNIQUE,
	"fecha_creacion" TIMESTAMP not null default now(),
	PRIMARY KEY("id_usuario")
);

CREATE TABLE IF NOT EXISTS "cuenta" (
	"id_cuenta" uuid NOT NULL DEFAULT gen_random_uuid(),
	"nombre" TEXT NOT NULL,
	"tipo" tipo_cuenta NOT NULL,
	"total" NUMERIC NOT NULL,
	"esta_invirtiendo" BOOLEAN,
	"tasa_anual" numeric not null,
	"id_usuario" uuid NOT NULL,
	"id_moneda" INTEGER NOT NULL,
	PRIMARY KEY("id_cuenta")
);

CREATE TABLE IF NOT EXISTS "movimiento" (
	"id_movimiento" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"tipo" tipo_movimiento NOT NULL,
	"estado" estado_movimiento NOT NULL,
	"observaciones" TEXT,
	"monto" NUMERIC NOT NULL,
	"monto_real" NUMERIC NOT NULL,
	"fecha_transaccion" TIMESTAMP NOT NULL,
	"fecha_creacion" TIMESTAMP NOT NULL DEFAULT now(),
	"fecha_actualizacion" TIMESTAMP,
	"id_categoria" INTEGER,
	"id_cuenta" uuid NOT NULL,
	"id_moneda" INTEGER NOT NULL,
	"id_comercio" INTEGER,
	"id_movimiento_padre" INTEGER,
	PRIMARY KEY("id_movimiento")
);

CREATE TABLE IF NOT EXISTS "categoria" (
	"id_categoria" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"nombre" TEXT NOT NULL,
	"tipo" tipo_flujo not null,
	"id_usuario" uuid,
	"id_categoria_padre" INTEGER,
	PRIMARY KEY("id_categoria")
);

CREATE TABLE IF NOT EXISTS "documento" (
	"id_documento" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"id_movimiento" INTEGER NOT NULL,
	"nombre_original" TEXT NOT NULL,
	"nombre_almacenado" TEXT NOT NULL,
	"tipo" TEXT NOT NULL,
	"tamanio" INTEGER NOT NULL,
	PRIMARY KEY("id_documento")
);

CREATE TABLE IF NOT EXISTS "moneda" (
	"id_moneda" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"nombre" TEXT NOT NULL,
	"simbolo" VARCHAR(5) NOT NULL,
	"codigo" VARCHAR(3) NOT NULL UNIQUE,
	PRIMARY KEY("id_moneda")
);

CREATE TABLE IF NOT EXISTS "comercio" (
	"id_comercio" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"nombre" TEXT NOT NULL,
	"direccion" TEXT NOT NULL,
	"id_usuario" uuid NOT NULL,
	PRIMARY KEY("id_comercio")
);

CREATE TABLE IF NOT EXISTS "recurrencia" (
	"id_recurrencia" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"nombre" TEXT NOT NULL,
	"frecuencia" INTEGER NOT NULL,
	"tipo" TEXT NOT NULL,
	"fecha_inicio" TIMESTAMP NOT NULL,
	"fecha_fin" TIMESTAMP,
	"activo" BOOLEAN NOT NULL,
	"id_usuario" uuid NOT NULL,
	"id_categoria" INTEGER,
	"id_movimiento" INTEGER,
	PRIMARY KEY("id_recurrencia")
);

CREATE TABLE IF NOT EXISTS "tarjeta_credito" (
	"id_tarjeta_credito" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"limite" NUMERIC NOT NULL,
	"dia_cierre" INTEGER NOT NULL,
	"dia_vencimiento" INTEGER NOT NULL,
	"id_cuenta" uuid NOT NULL,
	PRIMARY KEY("id_tarjeta_credito")
);

CREATE TABLE IF NOT EXISTS "etiqueta" (
	"id_etiqueta" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"id_usuario" uuid NOT NULL,
	"nombre" TEXT NOT NULL,
	"tipo" tipo_flujo NOT NULL,
	PRIMARY KEY("id_etiqueta")
);

CREATE TABLE IF NOT EXISTS "etiqueta_movimiento" (
	"id_movimiento" INTEGER NOT NULL,
	"id_etiqueta" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	PRIMARY KEY("id_movimiento", "id_etiqueta")
);

CREATE TABLE IF NOT EXISTS "producto" (
	"id_producto" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"id_usuario" uuid NOT NULL,
	"nombre" TEXT NOT NULL,
	"url" TEXT,
	"fecha_compra" TIMESTAMP NOT NULL,
	"fecha_llegada" TIMESTAMP NOT NULL,
	"total" NUMERIC NOT NULL,
	"id_movimiento" INTEGER NOT NULL,
	"id_comercio" INTEGER,
	PRIMARY KEY("id_producto")
);

